    for n, s, q, t, c, w in LORDSDAYS:
        out.append('{n:%d,s:"%s",q:"%s",t:"%s",c:"%s",w:"%s"}'
                   % (n, s, q, t.replace('"', '\\"'), c.replace('"', '\\"'), w.replace('"', '\\"')))
