    for d in deca:
        out.append('{no:"%s",q:"%s",name:"%s",text:"%s",req:"%s",forb:"%s",why:"%s",hc:"%s"}'
                   % (d["no"], d["q"], d["name"].replace('"', '\\"'), d["text"].replace('"', '\\"'),
                      d["req"].replace('"', '\\"'), d["forb"].replace('"', '\\"'),
                      d["why"].replace('"', '\\"'), d["hc"].replace('"', '\\"')))
    return "window.DECA=[" + ",".join(out) + "];"


